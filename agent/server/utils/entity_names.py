CHARACTER_NAMES: List[str] = sorted(CHARACTER_ALIASES.keys())


# ============================================================
#  公共解析函数（向后兼容）
# ============================================================

def resolve_location_from_query(query: str) -> Tuple[str, str]:
    """从用户查询中提取地点规范名。

    Returns:
        (canonical_name, matched_alias) — 若未匹配则 ("未指定", "")
    """
    if not query:
        return ("未指定", "")

    index = get_alias_index()
    # 按别名长度降序匹配 (优先匹配更具体的别名)
    sorted_aliases = sorted(index.keys(), key=len, reverse=True)
    for alias in sorted_aliases:
        if alias in query:
            return (index[alias], alias)
    return ("未指定", "")


def resolve_character_from_query(query: str) -> Optional[str]:
    """从用户查询中提取角色规范名。

    支持 CHARACTER_ALIASES 中的所有别名匹配。
    按别名长度降序匹配，优先命中更具体的别名。

    Returns:
        角色规范名, 若未匹配则 None
    """
    if not query:
        return None
    index = get_character_index()
    sorted_aliases = sorted(index.keys(), key=len, reverse=True)
    for alias in sorted_aliases:
        if alias in query:
            return index[alias]
    return None


def resolve_entity_from_query(query: str) -> Tuple[str, Optional[str], str]:
    """从用户查询中同时提取地点名、角色名、实体类型。

    Returns:
        (location_name, character_name, entity_type)
        entity_type: "location" | "character" | "unknown"
    """
    loc, _ = resolve_location_from_query(query)
    char = resolve_character_from_query(query)

    if loc != "未指定":
        return (loc, char, "location")
    if char:
        return ("未指定", char, "character")
    return ("未指定", None, "unknown")
